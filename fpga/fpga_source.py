"""Write the FPGA copy of the chip's top level.

The chip keeps its program memory in latches, which take about half the area
of flip-flops on the ASIC. FPGA tools handle latches badly, so the FPGA build
uses this copy, in which each word is a flip-flop written on the same pulse.
The harts are stopped while a program loads, so the one tick the flip-flop
takes over the latch changes nothing they see. Nothing else differs.

Run from the project root: python fpga/fpga_source.py [output file]
The default output is fpga/build/janus_chip_fpga.v.
"""
import os
import sys

LATCH = "always @* if (en) bits = wdata;"
FLOP = "always @(posedge clk) if (en) bits <= wdata;   // FPGA copy: a flip-flop, not a latch"


def main(out):
    with open(os.path.join("src", "janus_chip.v"), encoding="utf-8") as f:
        text = f.read()
    if text.count(LATCH) != 1:
        sys.exit("fpga_source.py: the program memory line in src/janus_chip.v changed; update LATCH")
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by fpga/fpga_source.py from src/janus_chip.v. Do not edit.\n")
        f.write(text.replace(LATCH, FLOP))
    print(out)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join("fpga", "build", "janus_chip_fpga.v"))

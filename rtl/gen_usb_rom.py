"""Write the USB program as a Verilog include for the proof in usb_ind.sv.

The proof names each instruction it reasons about. This script takes the
words and the trap registers from the assembler and checks that the program
still has the shape the proof was written for, so a change to protocols.usb()
cannot leave the proof passing on an old copy of the program.

Run from the project root: python3 rtl/gen_usb_rom.py <output-file>
"""
import os
import sys

sys.path.insert(0, os.getcwd())

import encode  # noqa: E402
import protocols  # noqa: E402
from janus import PUSH_PULL  # noqa: E402

NAMES = ["NRZI", "PAIR", "RESYNC", "POLY", "WIDTH0", "RESID", "XOR", "ONERR", "ONBRK",
         "CLAIM", "STUFF", "SYNC0", "SYNC6", "SYNCK", "PLOAD", "PID2", "PBR", "PCNT", "PID6",
         "WIDTH", "STORE", "CSTOP", "CRST", "BLOAD", "BYTE", "BJUMP",
         "CRC", "EOP", "EOP2", "J", "TURN", "NODATA", "CRCBAD",
         "ALOAD", "ASYNC0", "ASYNC6", "ASYNCK", "APID", "ASTORE", "AEOP", "AJ", "ATURN",
         "END", "END2", "LOOP", "TMO", "LWIDTH", "LBAD"]
SHAPE = (["mode"] * 9 + ["claim", "mode"]
         + ["bits"] * 3 + ["load", "bits", "branch", "counter", "bits", "mode", "store"]
         + ["choice", "choice", "load", "bits", "branch"]
         + ["bits"] * 5 + ["branch", "branch"]
         + ["load"] + ["bits"] * 4 + ["store"] + ["bits"] * 3
         + ["set", "set", "branch", "branch", "mode", "branch"])
LABELS = {"packet": 9, "pid": 18, "byte": 20, "crc": 26, "eop": 27, "eop2": 28,
          "end": 42, "tmo": 45, "lost": 46}
DWELL = 0x7FF  # a bit's length: the low 11 bits of the word
BITS, BRANCH, CHOICE = 1, 5, 6
ONERR, ONBRK = 7, 8   # the mode words that name the error and break handlers
SIZE = 64             # words of program memory


def main(path):
    prog = protocols.usb(16)
    count = len(prog.code)
    assert len(NAMES) == count and len(set(NAMES)) == count
    assert [ins.op for ins in prog.code] == SHAPE, "the USB program changed shape"
    assert list(prog.pins) == ["DP", "DM"] and set(prog.pins.values()) == {PUSH_PULL}
    assert prog.labels == LABELS and not prog.traps and len(prog.holds) == 1
    assert (encode.ROLE["A"], encode.ROLE["B"]) == (0, 1)
    words = encode.assemble(prog)
    timed = [w >> 28 == BITS for w in words]
    jumps = [w >> 28 in (BRANCH, CHOICE) or i in (ONERR, ONBRK) for i, w in enumerate(words)]
    base = [w & ~DWELL if t else w for w, t in zip(words, timed)]
    assert all(w & DWELL == 16 for w, t in zip(words, timed) if t)
    labels = {v: k for k, v in LABELS.items()}
    for i, (w, ins) in enumerate(zip(words, prog.code)):
        if w >> 28 in (BRANCH, CHOICE):
            assert w & 0x3F == LABELS[ins.args["label"]], i
    assert words[ONERR] & 0x3F == LABELS["end"]
    assert words[ONBRK] & 0x7F == 0x40 | LABELS["eop2"]
    assert all(labels.get(w & 0x3F) for w, j in zip(words, jumps) if j)
    cfg = encode.config_words(prog)
    assert cfg[0] == cfg[1] == cfg[3] == cfg[5] == 0 and cfg[4] == 18 * 16
    assert cfg[2] == (1 << 15) | (LABELS["tmo"] << 9) | (1 << 6) | (1 << 5)
    # What varies: the bit time, in every bit instruction and in the hold
    # trap's length (18 bit times); and the address the program is loaded
    # at, which moves every jump's target, the two handler addresses and the
    # hold trap's target.
    for bit in (5, 8, 11, 16, 50, 217, 2047):
        for at in (0, 1, 7, SIZE - count):
            expect = [w | bit if t else w + at if j else w
                      for w, t, j in zip(base, timed, jumps)]
            got = protocols.usb(bit)
            assert encode.assemble(got, at) == expect, (bit, at)
            assert encode.config_words(got, at) == [0, 0, cfg[2] + (at << 9), 0, 18 * bit, 0]
    lines = ["// Generated by rtl/gen_usb_rom.py from protocols.usb(). Do not edit.",
             f"localparam [5:0] PROG_LEN = 6'd{count};",
             f"localparam [5:0] MAX_START = 6'd{SIZE - count};"]
    lines += [f"localparam [5:0] PC_{name} = 6'd{i};" for i, name in enumerate(NAMES)]
    lines += ["// The word `at` places after the address `start` the program is loaded at.",
              "function automatic [31:0] usb_word(input [5:0] at, input [10:0] bit_t,",
              "                                 input [5:0] start, input [31:0] unwritten);",
              "    case (at)"]
    for i, (w, t, j) in enumerate(zip(base, timed, jumps)):
        value = f"32'h{w:08X}"
        if t:
            value += " | bit_t"
        elif j:
            value += " + start"
        lines.append(f"        6'd{i}: usb_word = {value};")
    lines += ["        default: usb_word = unwritten;", "    endcase", "endfunction",
              "// The hold trap: register 2 sends every hart to `tmo` once DM has",
              "// been high for the number of ticks in register 4, 18 bit times.",
              "function automatic [15:0] usb_hold(input [5:0] start);",
              f"    usb_hold = 16'h{cfg[2]:04X} + {{1'b0, start, 9'd0}};",
              "endfunction",
              "function automatic [15:0] usb_hold_ticks(input [10:0] bit_t);",
              "    usb_hold_ticks = 16'd18 * bit_t;",
              "endfunction", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"usb: {count} words", " ".join(f"{w:08X}" for w in base),
          f"hold {cfg[2]:04X}")


if __name__ == "__main__":
    main(sys.argv[1])

"""Write the CAN program as a Verilog include for the proof in can_ind.sv.

The proof names each instruction it reasons about. This script takes the
words and the trap registers from the assembler and checks that the program
still has the shape the proof was written for, so a change to protocols.can()
cannot leave the proof passing on an old copy of the program.

Run from the project root: python3 rtl/gen_can_rom.py <output-file>
"""
import os
import sys

sys.path.insert(0, os.getcwd())

import encode  # noqa: E402
import protocols  # noqa: E402
from janus import OPEN_DRAIN  # noqa: E402

NAMES = ["MSB", "RESYNC", "POLY", "WIDTH", "ONERR",
         "IDLE", "STUFF", "LOSE", "SOF",
         "LOAD1", "ID1", "STORE1", "LOAD2", "ID2", "STORE2", "LOAD3", "CTRL", "STORE3",
         "NOLOSE", "COUNT", "NODATA",
         "DLOAD", "DATA", "DSTORE", "DLOOP",
         "CRC", "UNSTUFF", "CRCDEL", "CRCBAD", "ACK",
         "TAIL", "TJUMP",
         "BADDEL", "BJUMP", "BAD"]
SHAPE = (["mode"] * 5 + ["claim", "mode", "mode", "bits"]
         + ["load", "bits", "store"] * 3
         + ["mode", "counter", "branch"]
         + ["load", "bits", "store", "branch"]
         + ["bits", "mode", "bits", "branch", "bits"]
         + ["bits", "branch"]
         + ["bits", "branch", "branch"])
LABELS = {"idle": 5, "data": 21, "crc": 25, "tail": 30, "crc_bad": 32, "bad": 34}
DWELL = 0x7FF  # a bit's length: the low 11 bits of the word
BITS, BRANCH = 1, 5
ONERR = 4      # the mode word that names the error handler's address
SIZE = 64      # words of program memory


def main(path):
    prog = protocols.can(8)
    count = len(prog.code)
    assert len(NAMES) == count and len(set(NAMES)) == count
    assert [ins.op for ins in prog.code] == SHAPE, "the CAN program changed shape"
    assert list(prog.pins) == ["BUS"] and prog.pins["BUS"] == OPEN_DRAIN
    assert prog.labels == LABELS and not prog.traps and len(prog.holds) == 1
    assert (encode.ROLE["S"], encode.ROLE["R"]) == (0, 1)
    words = encode.assemble(prog)
    timed = [w >> 28 == BITS for w in words]
    jumps = [w >> 28 == BRANCH or i == ONERR for i, w in enumerate(words)]
    base = [w & ~DWELL if t else w for w, t in zip(words, timed)]
    assert all(w & 0x3F == LABELS[ins.args["label"]]
               for w, ins in zip(words, prog.code) if w >> 28 == BRANCH)
    assert words[ONERR] & 0x3F == LABELS["bad"]
    cfg = encode.config_words(prog)
    assert cfg[0] == cfg[1] == cfg[3] == cfg[5] == 0 and cfg[4] == 20 * 8
    # What varies: the bit time, in every bit instruction and in the hold
    # trap's length (20 bit times); and the address the program is loaded
    # at, which moves every jump's target, the error handler's address and
    # the hold trap's target.
    for bit in (5, 8, 10, 50, 217, 2047):
        for at in (0, 1, 20, SIZE - count):
            expect = [w | bit if t else w + at if j else w
                      for w, t, j in zip(base, timed, jumps)]
            got = protocols.can(bit)
            assert encode.assemble(got, at) == expect, (bit, at)
            assert encode.config_words(got, at) == [0, 0, cfg[2] + (at << 9), 0, 20 * bit, 0]
    lines = ["// Generated by rtl/gen_can_rom.py from protocols.can(). Do not edit.",
             f"localparam [5:0] PROG_LEN = 6'd{count};",
             f"localparam [5:0] MAX_START = 6'd{SIZE - count};"]
    lines += [f"localparam [5:0] PC_{name} = 6'd{i};" for i, name in enumerate(NAMES)]
    lines += ["// The word `at` places after the address `start` the program is loaded at.",
              "function automatic [31:0] can_word(input [5:0] at, input [10:0] bit_t,",
              "                                 input [5:0] start, input [31:0] unwritten);",
              "    case (at)"]
    for i, (w, t, j) in enumerate(zip(base, timed, jumps)):
        value = f"32'h{w:08X}"
        if t:
            value += " | bit_t"
        elif j:
            value += " + start"
        lines.append(f"        6'd{i}: can_word = {value};")
    lines += ["        default: can_word = unwritten;", "    endcase", "endfunction",
              "// The hold trap: register 2 sends every hart to `idle` once the bus has",
              "// been recessive for the number of ticks in register 4, 20 bit times.",
              "function automatic [15:0] can_hold(input [5:0] start);",
              f"    can_hold = 16'h{cfg[2]:04X} + {{1'b0, start, 9'd0}};",
              "endfunction",
              "function automatic [15:0] can_hold_ticks(input [10:0] bit_t);",
              "    can_hold_ticks = 16'd20 * bit_t;",
              "endfunction", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"can: {count} words", " ".join(f"{w:08X}" for w in base),
          f"hold {cfg[2]:04X}")


if __name__ == "__main__":
    main(sys.argv[1])

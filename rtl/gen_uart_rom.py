"""Write the UART program as a Verilog include for the proof in uart_ind.sv.

The proof names each instruction it reasons about. This script takes the
words from the assembler and checks that the program still has the shape the
proof was written for, so a change to protocols.uart() cannot leave the proof
passing on an old copy of the program.

Run from the project root: python3 rtl/gen_uart_rom.py <output-file>
"""
import os
import sys

sys.path.insert(0, os.getcwd())

import encode  # noqa: E402
import protocols  # noqa: E402
from janus import PUSH_PULL  # noqa: E402

NAMES = ["SET", "IDLE", "CLAIM", "LOAD", "START", "DATA", "STORE", "STOP", "JUMP"]
SHAPE = ["set", "bits", "claim", "load", "bits", "bits", "store", "bits", "branch"]
DWELL = 0x7FF  # a timed bit's length: the low 11 bits of the word
BITS = 1       # opcode of a timed bit
SIZE = 64      # words of program memory


def main(path):
    prog = protocols.uart(8)
    assert [ins.op for ins in prog.code] == SHAPE, "the UART program changed shape"
    assert prog.pins == {"TX": PUSH_PULL} and prog.labels == {"idle": 2}
    assert encode.config_words(prog) == [0] * 6          # no traps
    assert (encode.ROLE["A"], encode.ROLE["B"]) == (0, 1)
    words = encode.assemble(prog)
    timed = [w >> 28 == BITS for w in words]
    base = [w & ~DWELL if t else w for w, t in zip(words, timed)]
    # Only two things vary: the bit time, in the timed bits, and the address
    # the program is loaded at, which moves the target of the one jump.
    jump = len(words) - 1
    for bit in (8, 9, 50, 217, 1024, 2047):
        for at in (0, 1, 20, SIZE - len(words)):
            expect = [w | bit if t else w for w, t in zip(base, timed)]
            expect[jump] += at
            assert encode.assemble(protocols.uart(bit), at) == expect, (bit, at)
    lines = ["// Generated by rtl/gen_uart_rom.py from protocols.uart(). Do not edit.",
             f"localparam [5:0] PROG_LEN = 6'd{len(words)};",
             f"localparam [5:0] MAX_START = 6'd{SIZE - len(words)};"]
    lines += [f"localparam [5:0] PC_{name} = 6'd{i};" for i, name in enumerate(NAMES)]
    lines += ["// The word `at` places after the address `start` the program is loaded at.",
              "function automatic [31:0] uart_word(input [5:0] at, input [10:0] bit_time,",
              "                                  input [5:0] start, input [31:0] unwritten);",
              "    case (at)"]
    for i, (w, t) in enumerate(zip(base, timed)):
        value = f"32'h{w:08X}" + (" | bit_time" if t else " + start" if i == jump else "")
        lines.append(f"        6'd{i}: uart_word = {value};")
    lines += ["        default: uart_word = unwritten;", "    endcase", "endfunction", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"uart: {len(words)} words", " ".join(f"{w:08X}" for w in base))


if __name__ == "__main__":
    main(sys.argv[1])

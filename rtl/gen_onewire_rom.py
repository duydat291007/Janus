"""Write the 1-Wire program as a Verilog include for the proof in onewire_ind.sv.

The proof names each instruction it reasons about. This script takes the
words and the trap registers from the assembler and checks that the program
still has the shape the proof was written for, so a change to
protocols.onewire() cannot leave the proof passing on an old copy.

Run from the project root: python3 rtl/gen_onewire_rom.py <output-file>
"""
import os
import sys

sys.path.insert(0, os.getcwd())

import encode  # noqa: E402
import protocols  # noqa: E402
from janus import OPEN_DRAIN  # noqa: E402

NAMES = ["NOARB", "CLAIM", "PULSE", "HANG", "SUSPECT", "SUSPECT_END", "SUSPECT_JUMP", "RESET", "RELEASE",
         "LOAD_PRESENCE", "PRESENCE", "STORE_PRESENCE", "WAIT", "LOAD_WRITE", "COUNT_WRITE",
         "W_START", "W_DATA", "W_REST", "W_LOOP", "W_STORE", "CHOICE", "LOAD_TOKEN", "LOAD_READ",
         "COUNT_READ", "R_START", "R_DATA", "R_REST", "R_LOOP", "R_STORE", "R_JUMP"]
SHAPE = ["mode", "claim", "bits", "branch", "bits", "bits", "branch", "bits", "bits", "load", "bits",
         "store", "bits", "load", "counter", "bits", "bits", "bits", "branch", "store", "choice",
         "load", "load", "counter", "bits", "bits", "bits", "branch", "store", "branch"]
# The timed steps the proof reasons about, named for their D_ parameter.
DWELLS = {"SUSP": "SUSPECT", "RESET": "RESET", "RELEASE": "RELEASE", "PRES": "PRESENCE",
          "WAIT": "WAIT", "START": "W_START", "WBIT": "W_DATA", "WREST": "W_REST",
          "RBIT": "R_DATA", "RREST": "R_REST"}
SIZE = 64      # words of program memory
JUMPS = (5, 6)  # opcodes whose low bits are a target address: branch and choice


def main(path):
    prog = protocols.onewire()
    count = len(prog.code)
    assert [ins.op for ins in prog.code] == SHAPE, "the 1-Wire program changed shape"
    assert prog.pins == {"DQ": OPEN_DRAIN} and not prog.traps and len(prog.holds) == 2
    assert (encode.ROLE["C"], encode.ROLE["T"]) == (0, 1)
    words = encode.assemble(prog)
    config = encode.config_words(prog)
    assert config[:2] == [0, 0]
    moved = [w >> 28 in JUMPS for w in words]
    # Only the load address varies: it moves every jump target and both traps'.
    for at in (0, 1, 20, SIZE - count):
        expect = [w + at if m else w for w, m in zip(words, moved)]
        assert encode.assemble(prog, at) == expect, at
        assert encode.config_words(prog, at) == [0, 0, config[2] + (at << 9),
                                                 config[3] + (at << 9), config[4], config[5]], at
    lines = ["// Generated by rtl/gen_onewire_rom.py from protocols.onewire(). Do not edit.",
             f"localparam [5:0] PROG_LEN = 6'd{count};",
             f"localparam [5:0] MAX_START = 6'd{SIZE - count};",
             f"localparam [15:0] HOLD_SUSPECT = 16'd{config[4]};",
             f"localparam [15:0] HOLD_RESET = 16'd{config[5]};"]
    # The step lengths, so the proof follows any change to the timings.
    d = {name: words[NAMES.index(at)] & 0x7FF for name, at in DWELLS.items()}
    assert d["START"] == words[NAMES.index("R_START")] & 0x7FF, "both slots start alike"
    hold_s, hold_r = config[4], config[5]
    # What the proof's formulas take for granted about the timings.
    assert d["START"] + d["RBIT"] // 2 == 15, "the controller reads a bit 15 ticks into its slot"
    assert 15 - d["START"] <= d["WBIT"] // 2 - 1, "the target reads a written bit inside it"
    assert d["WREST"] == 10, "the step from the last write slot to the first read slot assumes it"
    assert (words[NAMES.index("PULSE")] & 0x7FF) // 2 > hold_s, "the suspect trap ends the pulse step"
    assert hold_s + d["SUSP"] >= hold_r, "the reset trap fires before the line is let go"
    assert d["START"] + d["RBIT"] + d["RREST"] // 2 + 1 < hold_s, "a stray read slot ends first"
    assert d["RREST"] - d["RREST"] // 2 - 6 > d["WREST"] - d["WREST"] // 2 - 2
    assert hold_r + d["RESET"] + 2 + d["RELEASE"] < 1023 and d["PRES"] + d["WAIT"] + 2 < 1023
    assert d["RELEASE"] < 127
    lines += [f"localparam [11:0] D_{name} = 12'd{v};" for name, v in d.items()]
    lines += [f"localparam [5:0] PC_{name} = 6'd{i};" for i, name in enumerate(NAMES)]
    lines += ["// The word `at` places after the address `start` the program is loaded at.",
              "function automatic [31:0] ow_word(input [5:0] at, input [5:0] start,",
              "                                input [31:0] unwritten);",
              "    case (at)"]
    for i, (w, m) in enumerate(zip(words, moved)):
        lines.append(f"        6'd{i}: ow_word = 32'h{w:08X}{' + start' if m else ''};")
    lines += ["        default: ow_word = unwritten;", "    endcase", "endfunction",
              "// The trap registers the host writes: which of 2 to 5, for this load address.",
              "function automatic [15:0] ow_config(input [2:0] which, input [5:0] start);",
              "    case (which)",
              f"        3'd2: ow_config = 16'h{config[2]:04X} + {{1'b0, start, 9'd0}};",
              f"        3'd3: ow_config = 16'h{config[3]:04X} + {{1'b0, start, 9'd0}};",
              f"        3'd4: ow_config = 16'd{config[4]};",
              f"        3'd5: ow_config = 16'd{config[5]};",
              "        default: ow_config = 16'd0;", "    endcase", "endfunction", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"onewire: {count} words, traps {config[2]:04X} {config[3]:04X} at {config[4]} and {config[5]} ticks")


if __name__ == "__main__":
    main(sys.argv[1])

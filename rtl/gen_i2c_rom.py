"""Write the I2C program as a Verilog include for the proof in i2c_ind.sv.

The proof names each instruction it reasons about. This script takes the
words and the two trap registers from the assembler and checks that the
program still has the shape the proof was written for, so a change to
protocols.i2c() cannot leave the proof passing on an old copy of the program.

Run from the project root: python3 rtl/gen_i2c_rom.py <output-file>
"""
import os
import sys

sys.path.insert(0, os.getcwd())

import encode  # noqa: E402
import protocols  # noqa: E402
from janus import OPEN_DRAIN  # noqa: E402

NAMES = ["MSB", "CLK", "CLKOWN",
         "FREE", "IDLE", "START", "HANG",
         "ADDR", "SCLLOW", "LOADA", "ABYTE", "ASTORE", "MATCH", "LOADACK", "RW",
         "WACK", "WACKB",
         "WCHOOSE", "WRESTART", "WLOAD", "WBYTE", "WSTORE", "WLOADACK", "WACK2", "WACKB2",
         "WJUMP",
         "RACK", "RACKB",
         "RLOAD", "RBYTE", "RSTORE", "RLOADACK", "RACKBIT", "RACKB2", "RJUMP",
         "RS_SDA", "RS_SCL", "RS_FALL", "RS_JUMP",
         "SP_SDA", "SP_SCL", "SP_RISE", "SP_JUMP"]
SHAPE = (["mode"] * 3 + ["bits", "claim", "bits", "branch"]
         + ["bits", "bits", "load", "bits", "store", "match", "load", "branch"]
         + ["bits", "branch"]
         + ["choice", "choice", "load", "bits", "store", "load", "bits", "branch", "branch"]
         + ["bits", "branch"]
         + ["load", "bits", "store", "load", "bits", "branch", "branch"]
         + ["bits", "bits", "bits", "branch"]
         + ["bits", "bits", "bits", "branch"])
LABELS = {"idle": 3, "hang": 6, "addr": 7, "write_byte": 17, "read_ack": 26,
          "read_byte": 28, "restart": 35, "stop": 39}
PINS = ["SCL", "SDA"]
DWELL = 0x7FF  # a bit's length or half period: the low 11 bits of the word
BITS, BRANCH, CHOICE = 1, 5, 6
SIZE = 64      # words of program memory


def main(path):
    prog = protocols.i2c(8)
    count = len(prog.code)
    assert len(NAMES) == count and len(set(NAMES)) == count
    assert [ins.op for ins in prog.code] == SHAPE, "the I2C program changed shape"
    assert list(prog.pins) == PINS and all(v == OPEN_DRAIN for v in prog.pins.values())
    assert prog.labels == LABELS and len(prog.traps) == 2 and not prog.holds
    assert (encode.ROLE["C"], encode.ROLE["T"]) == (0, 1)
    words = encode.assemble(prog)
    timed = [w >> 28 == BITS for w in words]
    jumps = [w >> 28 in (BRANCH, CHOICE) for w in words]
    base = [w & ~DWELL if t else w for w, t in zip(words, timed)]
    assert all(w & 0x3F == LABELS[ins.args["label"]]
               for w, j, ins in zip(words, jumps, prog.code) if j)
    traps = encode.config_words(prog)
    assert traps[2:] == [0] * 4
    # What varies: the half period, in every bit instruction, and the address
    # the program is loaded at, which moves every jump's target and the traps'.
    for half in (5, 8, 10, 217, 2047):
        for at in (0, 1, 20, SIZE - count):
            expect = [w | half if t else w + at if j else w
                      for w, t, j in zip(base, timed, jumps)]
            got = protocols.i2c(half)
            assert encode.assemble(got, at) == expect, (half, at)
            assert encode.config_words(got, at) == [t + (at << 9) for t in traps[:2]] + [0] * 4
    lines = ["// Generated by rtl/gen_i2c_rom.py from protocols.i2c(). Do not edit.",
             f"localparam [5:0] PROG_LEN = 6'd{count};",
             f"localparam [5:0] MAX_START = 6'd{SIZE - count};"]
    lines += [f"localparam [5:0] PC_{name} = 6'd{i};" for i, name in enumerate(NAMES)]
    lines += [f"localparam [1:0] PIN_{name} = 2'd{i};" for i, name in enumerate(PINS)]
    lines += ["// The word `at` places after the address `start` the program is loaded at.",
              "function automatic [31:0] i2c_word(input [5:0] at, input [10:0] half,",
              "                                 input [5:0] start, input [31:0] unwritten);",
              "    case (at)"]
    for i, (w, t, j) in enumerate(zip(base, timed, jumps)):
        value = f"32'h{w:08X}"
        if t:
            value += " | half"
        elif j:
            value += " + start"
        lines.append(f"        6'd{i}: i2c_word = {value};")
    lines += ["        default: i2c_word = unwritten;", "    endcase", "endfunction",
              "// Trap registers 0 and 1: STOP sends every hart to `idle`, START to `addr`.",
              "function automatic [15:0] i2c_trap(input i, input [5:0] start);",
              f"    i2c_trap = (i ? 16'h{traps[1]:04X} : 16'h{traps[0]:04X}) + {{1'b0, start, 9'd0}};",
              "endfunction", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"i2c: {count} words", " ".join(f"{w:08X}" for w in base),
          f"traps {traps[0]:04X} {traps[1]:04X}")


if __name__ == "__main__":
    main(sys.argv[1])

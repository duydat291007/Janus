"""Write the SPI program as a Verilog include for the proof in spi_ind.sv.

The proof names each instruction it reasons about. This script takes the
words and the trap register from the assembler and checks that the program
still has the shape the proof was written for, so a change to protocols.spi()
cannot leave the proof passing on an old copy of the program.

Run from the project root: python3 rtl/gen_spi_rom.py <output-file>
"""
import os
import sys

sys.path.insert(0, os.getcwd())

import encode  # noqa: E402
import protocols  # noqa: E402
from janus import PUSH_PULL  # noqa: E402

NAMES = ["MSB", "CLK", "OWNER", "CPOL", "CPHA", "LANE", "SETCS", "SETCK", "IDLE", "CLAIM",
         "SELECT", "LOADC", "LOADT", "DATA", "DESELECT", "JUMP"]
SHAPE = ["mode"] * 6 + ["set", "set", "set", "claim", "bits", "load", "load", "bits", "bits",
                        "branch"]
PINS = ["CS", "SCK", "MOSI", "MISO"]
DWELL = 0x7FF  # a bit's length or half period: the low 11 bits of the word
BITS = 1       # opcode of a bit instruction
SIZE = 64      # words of program memory
CPOL_WORD, CPHA_WORD, SETCK_WORD = 3, 4, 7
SETCK_LEVEL = 1 << 21    # `set` drives this level


def main(path):
    prog = protocols.spi(8)
    count = len(prog.code)
    assert [ins.op for ins in prog.code] == SHAPE, "the SPI program changed shape"
    assert list(prog.pins) == PINS and not any(prog.pins.values())   # all push-pull
    assert PUSH_PULL is False
    assert prog.labels == {"idle": 8} and len(prog.traps) == 1 and not prog.holds
    assert (encode.ROLE["C"], encode.ROLE["T"]) == (0, 1)
    words = encode.assemble(prog)
    timed = [w >> 28 == BITS for w in words]
    base = [w & ~DWELL if t else w for w, t in zip(words, timed)]
    trap = encode.config_words(prog)
    assert trap[1:] == [0] * 5
    jump = count - 1
    # What varies: the half period, in the three bit instructions; the clock
    # polarity and phase, each in its mode word and the polarity also in the
    # level the clock is set to; and the address the program is loaded at,
    # which moves the jump's target and the trap's.
    for half in (5, 8, 10, 217, 2047):
        for cpol in (0, 1):
            for cpha in (0, 1):
                for at in (0, 1, 20, SIZE - count):
                    expect = [w | half if t else w for w, t in zip(base, timed)]
                    expect[CPOL_WORD] |= cpol
                    expect[CPHA_WORD] |= cpha
                    expect[SETCK_WORD] |= cpol * SETCK_LEVEL
                    expect[jump] += at
                    got = protocols.spi(half, cpol, cpha)
                    assert encode.assemble(got, at) == expect, (half, cpol, cpha, at)
                    assert encode.config_words(got, at) == [trap[0] + (at << 9)] + [0] * 5
    lines = ["// Generated by rtl/gen_spi_rom.py from protocols.spi(). Do not edit.",
             f"localparam [5:0] PROG_LEN = 6'd{count};",
             f"localparam [5:0] MAX_START = 6'd{SIZE - count};"]
    lines += [f"localparam [5:0] PC_{name} = 6'd{i};" for i, name in enumerate(NAMES)]
    lines += [f"localparam [1:0] PIN_{name} = 2'd{i};" for i, name in enumerate(PINS)]
    lines += ["// The word `at` places after the address `start` the program is loaded at.",
              "function automatic [31:0] spi_word(input [5:0] at, input [10:0] half,",
              "                                 input cpol, input cpha, input [5:0] start,",
              "                                 input [31:0] unwritten);",
              "    case (at)"]
    for i, (w, t) in enumerate(zip(base, timed)):
        value = f"32'h{w:08X}"
        if t:
            value += " | half"
        elif i == CPOL_WORD:
            value += " | cpol"
        elif i == CPHA_WORD:
            value += " | cpha"
        elif i == SETCK_WORD:
            value += " | {cpol, 21'd0}"
        elif i == jump:
            value += " + start"
        lines.append(f"        6'd{i}: spi_word = {value};")
    lines += ["        default: spi_word = unwritten;", "    endcase", "endfunction",
              "// Trap register 0: a rising CS sends every hart to `idle`.",
              "function automatic [15:0] spi_trap(input [5:0] start);",
              f"    spi_trap = 16'h{trap[0]:04X} + {{1'b0, start, 9'd0}};",
              "endfunction", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"spi: {count} words", " ".join(f"{w:08X}" for w in base), f"trap {trap[0]:04X}")


if __name__ == "__main__":
    main(sys.argv[1])
